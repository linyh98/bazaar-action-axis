    public static class Triggers
    {
        public static void FireSkillStart(BattleContext ctx)
        {
            foreach (InternalItem skill in ctx.Skills)
                foreach (TriggerDef trigger in skill.Card.Triggers)
                    if (!ctx.IsTrainingDummySource(skill.Side) && trigger.Event == "atCombatStart" && NativeSkillSupport.PrerequisitesMatch(ctx, skill, trigger.SkillRule))
                        FireSkill(ctx, skill, trigger, 0, 0, null, null);
        }

        private static void FireSkill(BattleContext ctx, InternalItem skill, TriggerDef trigger, double time,
            int depth, int? chainId, string triggerSourceId, string triggerTargetId = null)
        {
            int chain = chainId.HasValue ? chainId.Value : ctx.NextChainId++;
            BattleEvent ev = new BattleEvent();
            ev.Time = time;
            ev.Side = skill.Side;
            ev.SourceItemId = skill.Id;
            ev.SourceCardId = skill.CardId;
            ev.Kind = "skillTrigger";
            ev.ChainId = chain;
            ev.Depth = depth;
            ctx.Events.Add(Effects.FinishEvent(ctx, ev));
            foreach (Effect effect in trigger.Effects)
                Effects.ResolveEffect(ctx, effect, skill, time, depth + 1, chain, triggerSourceId, triggerTargetId);
        }

        private static readonly HashSet<string> SourceScoped = new HashSet<string>
        {
            "onHeal",
            "onShield",
            "onBurnApplied",
            "onPoisonApplied",
            "onRegen",
            "onHaste",
            "onSlow",
            "onFreeze",
            "onCrit",
            "onReload",
            "onDestroy",
            "onCharge",
            "onOverHeal",
            "onFly",
            "onFlyStop",
            "onBeforeUse"
        };

        public static void Enqueue(BattleContext ctx, TriggerPayload payload)
        {
            if (ctx.Config.NativeMechanics && payload.NativeQueueOrder == 0)
                payload.NativeQueueOrder = ++ctx.NativeQueueSequence;
            ctx.TriggerQueue.Enqueue(payload);
        }

        public static void Drain(BattleContext ctx, double time)
        {
            Drain(ctx, time, false, null, false);
        }

        // 只结算指定事件，其余事件留在队列里按原生帧序执行。
        public static void DrainEvent(BattleContext ctx, double time, string eventName)
        {
            Drain(ctx, time, false, eventName, false);
        }

        // 死亡结算期间的销毁/禁用观察者仍须执行：Elixir of Immortality 的
        // 首次致死就是“自禁用 -> 摧毁前 -> ReviveHeal”；若这里按 HP<=0
        // 直接清空队列，复活永远不会发生。
        public static void DrainEventWhileDead(BattleContext ctx, double time, string eventName)
        {
            Drain(ctx, time, false, eventName, true);
        }

        // 死亡触发需要在一方 HP 已归零时仍能结算（复活/回血）。
        public static void DrainWhileDead(BattleContext ctx, double time)
        {
            Drain(ctx, time, false, null, true);
        }

        // Native frame logs show performed-action passives firing on the next
        // 50 ms frame. New triggers generated by a passive stay queued for the
        // following frame instead of collapsing the entire chain into one tick.
        public static void DrainNativeFrame(BattleContext ctx, double time, bool splitPriorities = false)
        {
            Drain(ctx, time, true, null, false);
            // Deferred ability effects may themselves emit new trigger events.
            // Run them after this frame's bounded drain so their children stay
            // queued for the next native frame.
            DrainDeferredNative(ctx, time, false);
            if (!splitPriorities)
            {
                DrainNativeAfterEarlierCast(ctx, time, long.MaxValue);
                DrainDeferredNative(ctx, time, true);
            }
        }

        // Low/Lowest observers follow the already scheduled card actions.
        // Their children remain queued for the following native frame.
        public static void DrainNativeLateFrame(BattleContext ctx, double time)
        {
            DrainDeferredNative(ctx, time, true);
        }

        private static bool LatePriority(TriggerDef trigger)
        {
            return trigger.Priority == "Low" || trigger.Priority == "Lowest";
        }

        private static bool CanObserve(BattleContext ctx, InternalItem owner, TriggerPayload payload)
        {
            if (owner == null) return false;
            if (owner.Destroyed)
                // A before-destroy batch can transform its owner before its
                // remaining, already matched abilities finish (Abducted Cow).
                return payload.Event == "onBeforeDestroy" && (owner.Destroying || owner.Disabling);
            if (!ctx.Config.NativeMechanics || !owner.Disabled) return true;
            // A disabled item no longer runs ordinary combat passives. The
            // lifecycle chain must still complete: before-destroy transforms,
            // disabled/repair notifications, and death recovery remain valid.
            return payload.Event == "onBeforeDestroy" || payload.Event == "onCardDisabled" ||
                payload.Event == "onCardDestroyed" || payload.Event == "onCardRepaired" ||
                payload.Event == "onCardTransformed" || payload.Event == "onPlayerDied";
        }

        private static void DrainDeferredNative(BattleContext ctx, double time, bool late)
        {
            List<DeferredNativeTrigger> due = ctx.DeferredNativeTriggers
                .Where(delegate(DeferredNativeTrigger entry) { return !entry.AfterEarlierCast && entry.DueAt <= time + 1e-9 && LatePriority(entry.Match.Trigger) == late; })
                .OrderBy(delegate(DeferredNativeTrigger entry) { return entry.DueAt; }).ToList();
            foreach (DeferredNativeTrigger entry in due)
            {
                if (!late && entry.Match.Trigger.Priority == "Medium" && ctx.NativePeriodicBeforeObservers)
                {
                    entry.AfterEarlierCast = true;
                    continue;
                }
                ctx.DeferredNativeTriggers.Remove(entry);
                if (ctx.Ended || entry.Match.Owner.Destroyed || entry.Match.Owner.Generation != entry.Generation) continue;
                if (!late && !ctx.Config.EnemyIsTrainingDummy && (ctx.Player.Hp <= 0 || ctx.Enemy.Hp <= 0)) break;
                ctx.PushTriggerAmount(entry.Payload.Amount);
                try { ExecuteMatched(ctx, entry.Match, entry.Payload, time); }
                finally { ctx.PopTriggerAmount(); }
            }
        }

        // A cast reserved before an onUse observer keeps its place. Charge can
        // reserve another card during the parent cast, before publishing onUse.
        public static void DrainNativeAfterEarlierCast(BattleContext ctx, double time, long beforeOrder, InternalItem nextCast = null)
        {
            List<DeferredNativeTrigger> due = ctx.DeferredNativeTriggers
                .Where(delegate(DeferredNativeTrigger entry) { return entry.AfterEarlierCast &&
                    entry.DueAt <= time + 1e-9 && (entry.Payload.NativeQueueOrder < beforeOrder ||
                    entry.Match.Owner == nextCast); })
                .OrderBy(delegate(DeferredNativeTrigger entry) { return entry.Payload.NativeQueueOrder; }).ToList();
            foreach (DeferredNativeTrigger entry in due)
            {
                ctx.DeferredNativeTriggers.Remove(entry);
                if (ctx.Ended || entry.Match.Owner.Generation != entry.Generation) continue;
                ctx.PushTriggerAmount(entry.Payload.Amount);
                try { ExecuteMatched(ctx, entry.Match, entry.Payload, time); }
                finally { ctx.PopTriggerAmount(); }
            }
        }

        private static void ResolveMatched(BattleContext ctx, DeferredTriggerMatch match, TriggerPayload payload, double time, bool nativeFrame)
        {
            if (!CanObserve(ctx, match.Owner, payload)) return;
            // Immediate observers are deliberately exempt: native ledgers show
            // them running on adjacent frames. Every non-Immediate ability has
            // a shared execution queue, including events from different cards
            // (Tempering: native frames 101, 106, 111 in b1621).
            bool selfCharge = match.Trigger.Effects.Count == 1 && match.Trigger.Effects[0].Kind == "charge" &&
                match.Trigger.Effects[0].Target != null && match.Trigger.Effects[0].Target.Kind == "selfItem";
            // Self-charge already has the same 250 ms queue in Effects. Reuse
            // that queue instead of reserving the same delay in two places.
            if (ctx.Config.NativeMechanics && nativeFrame && !selfCharge &&
                !string.IsNullOrEmpty(match.Trigger.Priority) && match.Trigger.Priority != "Immediate")
            {
                Dictionary<TriggerDef, double> next;
                if (!ctx.NativeTriggerNextAt.TryGetValue(match.Owner, out next))
                {
                    next = new Dictionary<TriggerDef, double>();
                    ctx.NativeTriggerNextAt[match.Owner] = next;
                }
                double available;
                double dueAt = next.TryGetValue(match.Trigger, out available) ? Math.Max(time, available) : time;
                next[match.Trigger] = JsMath.RoundTo6(dueAt + 0.25);
                if (dueAt > time + 1e-9)
                {
                    // Do not retain DeferredMatches/BeforeUseStage from the
                    // shared payload; only the original event context belongs
                    // to this single matched observer.
                    TriggerPayload saved = new TriggerPayload { Event = payload.Event,
                        SourceSide = payload.SourceSide, SourceItemId = payload.SourceItemId,
                        TargetSide = payload.TargetSide, TargetItemId = payload.TargetItemId,
                        ActorSide = payload.ActorSide, ActorItemId = payload.ActorItemId,
                        AttributeName = payload.AttributeName, ChangeType = payload.ChangeType,
                        Amount = payload.Amount, ChainId = payload.ChainId, Depth = payload.Depth,
                        NativeQueueOrder = ++ctx.NativeQueueSequence };
                    ctx.DeferredNativeTriggers.Add(new DeferredNativeTrigger { Match = match,
                        Payload = saved, DueAt = dueAt, Generation = match.Owner.Generation,
                        AfterEarlierCast = match.Trigger.Priority == "Medium" && payload.Event == "onUse" });
                    return;
                }
            }
            if (ctx.Config.NativeMechanics && nativeFrame && LatePriority(match.Trigger))
            {
                ctx.DeferredNativeTriggers.Add(new DeferredNativeTrigger { Match = match,
                    Payload = payload, DueAt = time, Generation = match.Owner.Generation });
                return;
            }
            // 完成动作观察者（onFreeze/onPoisonApplied/onBurnApplied 等由 Effects.EmitTrigger
            // 直接入队，没有 NativeQueueOrder）在本帧有施放时须排到这些施放之后：07ae8be8
            // 帧121 的 Yeti Crab 冰冻反应（Medium）晚于同帧 Jellyfish 施放，读到施放前的
            // PoisonApplyAmount=3；若先加 +2 会读到 5，玩家毒 9+5=14 而非 9+3=12。
            // 0c811484 frame 245: Medium onHaste growth follows already
            // queued card actions too; the regen cast still reads 20, then
            // its RegenApplyAmount grows to 24 on this same frame.
            bool performedActionObserver = payload.Event == "onFreeze" || payload.Event == "onHaste";
            if (ctx.Config.NativeMechanics && nativeFrame && match.Trigger.Priority == "Medium" &&
                (ctx.NativePeriodicBeforeObservers ||
                ctx.NativeEarliestDueCastOrder > 0 &&
                (performedActionObserver || payload.Event == "onUse" &&
                payload.NativeQueueOrder > ctx.NativeEarliestDueCastOrder)))
            {
                TriggerPayload queued = payload;
                if (performedActionObserver)
                {
                    // 与 ExecuteNativeCasts 末尾 DrainNativeAfterEarlierCast(long.MaxValue)
                    // 的批次对齐：占一个最大序号，避免逐个施放前被取出。
                    queued = new TriggerPayload { Event = payload.Event, SourceSide = payload.SourceSide,
                        SourceItemId = payload.SourceItemId, TargetSide = payload.TargetSide,
                        TargetItemId = payload.TargetItemId, ActorSide = payload.ActorSide,
                        ActorItemId = payload.ActorItemId, AttributeName = payload.AttributeName,
                        ChangeType = payload.ChangeType, Amount = payload.Amount,
                        ChainId = payload.ChainId, Depth = payload.Depth,
                        NativeQueueOrder = long.MaxValue - 1 };
                }
                ctx.DeferredNativeTriggers.Add(new DeferredNativeTrigger { Match = match,
                    Payload = queued, DueAt = time, Generation = match.Owner.Generation, AfterEarlierCast = true });
                return;
            }
            ExecuteMatched(ctx, match, payload, time);
        }

        private static void ExecuteMatched(BattleContext ctx, DeferredTriggerMatch match, TriggerPayload payload, double time)
        {
            // Recheck execution eligibility for observers already queued before
            // disable, without re-evaluating their snapshotted prerequisites.
            if (!CanObserve(ctx, match.Owner, payload)) return;
            if (match.IsSkill)
                FireSkill(ctx, match.Owner, match.Trigger, time, payload.Depth, payload.ChainId, payload.SourceItemId, payload.TargetItemId);
            else
                foreach (Effect effect in match.Trigger.Effects)
                    Effects.ResolveEffect(ctx, effect, match.Owner, time, payload.Depth + 1, payload.ChainId, payload.SourceItemId, payload.TargetItemId);
        }

        // 终局快照：结算仍未匹配的观察者；Effects.ResolveEffect 在
        // TerminalAttributesOnly 下只放行确定性属性反应。
        public static void ResolveTerminal(BattleContext ctx, TriggerPayload payload, double time)
        {
            ResolvePayload(ctx, payload, time, false, true);
        }

        public static void BeginNativeUse(BattleContext ctx, TriggerPayload payload, double time)
        {
            payload.BeforeUseStage = 1;
            ResolvePayload(ctx, payload, time);
        }

        public static void EndNativeUse(BattleContext ctx, TriggerPayload payload, double time)
        {
            payload.BeforeUseStage = 2;
            ResolvePayload(ctx, payload, time);
            payload.BeforeUseStage = 0;
            if (payload.DeferredMatches != null && payload.DeferredMatches.Count > 0)
                Enqueue(ctx, payload);
        }

        // onUse 被动按 EffectPriority 分帧：Immediate 在使用帧同帧结算
        // （ebde2082：Quick Ignition/Grease Fire 的 Immediate modifyAttribute
        // 与被用物品自身效果同帧，Medium 的 Haste/Burn 下一帧）；
        // 其余优先级仍由下一帧 DrainNativeFrame 结算（170666bf 的
        // Matchbox Medium 充能为使用+1 帧）。
        public static void DrainImmediateOnUse(BattleContext ctx, double time)
        {
            DrainImmediateEvent(ctx, time, "onUse");
        }

        public static void DrainImmediateActions(BattleContext ctx, double time)
        {
            // Health/Shield/Rage changes are performed-action observations too.
            // Snapshot their non-Immediate matches before Immediate counters
            // mutate prerequisites (Trollosaur: count now, disable next frame).
            DrainImmediateEvent(ctx, time, null, true);
        }

        // A lethal critical still publishes its Immediate counters before
        // CombatantDied (0a81ce frame 268, Alacrity). Other performed actions
        // and next-frame observers retain the terminal settlement path.
        public static void DrainImmediateCriticals(BattleContext ctx, double time)
        {
            bool previousTerminalMode = ctx.TerminalAttributesOnly;
            ctx.TerminalAttributesOnly = true;
            try { DrainImmediateEvent(ctx, time, "onCrit"); }
            finally { ctx.TerminalAttributesOnly = previousTerminalMode; }
        }

        public static void DrainImmediatePlayerAttributes(BattleContext ctx, double time)
        {
            DrainImmediateEvent(ctx, time, "onPlayerAttributeChanged", true);
        }

        // 禁用等同摧毁：Immediate 优先级的“摧毁前”被动与禁用同帧结算。
        // 07f044ee 帧 140：Oblivion Vortex 禁用 The Big One 后，Big One 的
        // Immediate PlayerDamage/Poison 同帧落地（伤害取禁用前的实时属性），
        // 而 Vortex 自身 Low 优先级的充能观察者仍是下一帧。
        public static void DrainImmediateBeforeDestroy(BattleContext ctx, double time)
        {
            DrainImmediateEvent(ctx, time, "onBeforeDestroy");
        }

        private static bool HasImmediatePlayerAttributeListener(BattleContext ctx, TriggerPayload payload, bool checkEligibility = true)
        {
            List<InternalItem> owners = new List<InternalItem>(ctx.Items);
            owners.AddRange(ctx.Skills);
            InternalItem source = FindItem(ctx, payload.SourceItemId);
            if (source == null) source = ctx.Skills.Find(delegate(InternalItem skill) { return skill.Id == payload.SourceItemId; });
            foreach (InternalItem owner in owners)
            {
                if (!CanObserve(ctx, owner, payload) || ctx.IsTrainingDummySource(owner.Side)) continue;
                foreach (TriggerDef trigger in owner.Card.Triggers)
                {
                    if (trigger.Event != "onPlayerAttributeChanged" || trigger.Priority != "Immediate" ||
                        !AttributesMatch(trigger, payload)) continue;
                    if (trigger.SkillRule == null) { if (!owner.IsSkill) return true; continue; }
                    // A matching Immediate listener still consumes this event's
                    // observation window when its current HP/counter gate is false.
                    if (!checkEligibility && trigger.SkillRule.PlayerOwner != null)
                    {
                        bool same = owner.Side == payload.SourceSide;
                        if (trigger.SkillRule.PlayerOwner == "self" ? same : !same) return true;
                        continue;
                    }
                    bool matches = payload.Global
                        ? trigger.Filter == null && GlobalMatches(ctx, owner, trigger.SkillRule, checkEligibility)
                        : trigger.SkillRule.PlayerOwner != null
                            ? PlayerMatches(ctx, owner, payload, trigger)
                            : NativeMatches(ctx, owner, source, trigger, payload, checkEligibility);
                    if (matches) return true;
                }
            }
            return false;
        }

        private static void DrainImmediateEvent(BattleContext ctx, double time, string onlyEvent, bool playerAttributes = false)
        {
            int remaining = ctx.TriggerQueue.Count;
            Queue<TriggerPayload> deferred = new Queue<TriggerPayload>();
            bool aborted = false;
            while (ctx.TriggerQueue.Count > 0 && remaining-- > 0)
            {
                if (ctx.Ended)
                {
                    ctx.TriggerQueue.Clear();
                    aborted = true;
                    break;
                }
                if (ctx.EventsThisTick > ctx.Rules.MaxEventsPerTick)
                {
                    ctx.Warnings.Add("event cap reached at t=" + time.ToString());
                    ctx.TriggerQueue.Clear();
                    aborted = true;
                    break;
                }
                TriggerPayload payload = ctx.TriggerQueue.Dequeue();
                bool playerAttributeEvent = playerAttributes && payload.Event == "onPlayerAttributeChanged";
                bool eligibleImmediate = playerAttributeEvent && HasImmediatePlayerAttributeListener(ctx, payload);
                if (onlyEvent == null && playerAttributeEvent && !eligibleImmediate &&
                    HasImmediatePlayerAttributeListener(ctx, payload, false))
                {
                    // 0624335c frame 200: Poison leaves HP above half, then Burn
                    // crosses it. Never reconsider the Poison event's false Panic
                    // gate after Burn. With no eligible Immediate listener, leave
                    // ordinary observers for their existing next-frame evaluation.
                    payload.ImmediateSettled = true;
                    deferred.Enqueue(payload);
                    continue;
                }
                // Without an Immediate listener, leave player-attribute events
                // for their normal frame. Early snapshots would let a nested
                // Medium Rage reaction bypass a counter updated later this frame.
                bool immediateAttributes = playerAttributeEvent && (onlyEvent != null || eligibleImmediate);
                bool performedAction = payload.Event == "onUse" || SourceScoped.Contains(payload.Event) || immediateAttributes;
                if ((onlyEvent != null && payload.Event != onlyEvent) || (onlyEvent == null && !performedAction) ||
                    payload.Event == "onBeforeUse" ||
                    payload.ImmediateSettled || payload.Depth > ctx.Rules.MaxTriggerDepth)
                {
                    deferred.Enqueue(payload);
                    continue;
                }
                payload.ImmediateSettled = true;
                ctx.PushTriggerAmount(payload.Amount);
                try { ResolvePayload(ctx, payload, time, true); }
                finally { ctx.PopTriggerAmount(); }
                deferred.Enqueue(payload);
            }
            if (!aborted)
                while (deferred.Count > 0) ctx.TriggerQueue.Enqueue(deferred.Dequeue());
        }

        private static void Drain(BattleContext ctx, double time, bool oneFrame, string onlyEvent, bool allowDead)
        {
            int remaining = ctx.TriggerQueue.Count;
            Queue<TriggerPayload> deferred = new Queue<TriggerPayload>();
            bool aborted = false;
            while (ctx.TriggerQueue.Count > 0 && (!oneFrame || remaining-- > 0))
            {
                if (!allowDead && !ctx.Config.EnemyIsTrainingDummy && (ctx.Player.Hp <= 0 || ctx.Enemy.Hp <= 0))
                {
                    ctx.TriggerQueue.Clear();
                    aborted = true;
                    break;
                }

                if (ctx.EventsThisTick > ctx.Rules.MaxEventsPerTick)
                {
                    ctx.Warnings.Add("event cap reached at t=" + time.ToString());
                    BattleEvent cap = new BattleEvent();
                    cap.Time = time;
                    cap.Side = Side.Player;
                    cap.Kind = "warning";
                    cap.Value = 0;
                    cap.Note = "event cap reached";
                    cap.ChainId = ctx.NextChainId++;
                    cap.Depth = 0;
                    cap.Id = ctx.NextEventId++;
                    ctx.Events.Add(cap);
                    ctx.TriggerQueue.Clear();
                    aborted = true;
                    break;
                }

                TriggerPayload payload = ctx.TriggerQueue.Dequeue();
                if (onlyEvent != null && payload.Event != onlyEvent)
                {
                    deferred.Enqueue(payload);
                    continue;
                }
                if (payload.Depth > ctx.Rules.MaxTriggerDepth)
                {
                    ctx.Warnings.Add("trigger depth cap reached at t=" + time.ToString());
                    BattleEvent depthCap = new BattleEvent();
                    depthCap.Time = time;
                    depthCap.Side = payload.SourceSide;
                    depthCap.Kind = "warning";
                    depthCap.Value = 0;
                    depthCap.Note = "trigger depth cap reached";
                    depthCap.ChainId = payload.ChainId.HasValue ? payload.ChainId.Value : ctx.NextChainId++;
                    depthCap.Depth = 0;
                    depthCap.Id = ctx.NextEventId++;
                    ctx.Events.Add(depthCap);
                    continue;
                }

                ctx.PushTriggerAmount(payload.Amount);
                try { ResolvePayload(ctx, payload, time, false, oneFrame); }
                finally { ctx.PopTriggerAmount(); }
            }
            if (!aborted)
                while (deferred.Count > 0) ctx.TriggerQueue.Enqueue(deferred.Dequeue());
        }

        // TReferenceValueAttributeChange 需要通过 TriggerAmount 读取本次变化量，
        // 因此同一个 payload 下所有被动都必须在这个作用域内结算。
        // immediateOnly=true 只结算 Immediate 优先级（同帧分帧）；常规结算跳过
        // 已同帧结算过的 Immediate 部分（payload.ImmediateSettled）。
        private static void ResolvePayload(BattleContext ctx, TriggerPayload payload, double time, bool immediateOnly = false, bool nativeFrame = false)
        {
            // 使用帧快照的延迟匹配：只执行，不再重评前提（Immediate 计数能力
            // 已同帧 +1，不能让 Medium 的判定在下一帧看到新值而失效）。
            if (!immediateOnly && payload.BeforeUseStage == 0 && payload.DeferredMatches != null)
            {
                List<DeferredTriggerMatch> matches = payload.DeferredMatches;
                payload.DeferredMatches = null;
                foreach (DeferredTriggerMatch match in matches)
                {
                    if (!CanObserve(ctx, match.Owner, payload)) continue;
                    ResolveMatched(ctx, match, payload, time, nativeFrame);
                }
                return;
            }
            InternalItem sourceItem = null;
            if (!string.IsNullOrEmpty(payload.SourceItemId))
            {
                foreach (InternalItem item in ctx.Items)
                {
                    if (item.Id == payload.SourceItemId)
                    {
                        sourceItem = item;
                        break;
                    }
                }
                // 技能自身的 onHeal/onDamageDealt 等事件也带技能实例 ID；
                // 只查 ctx.Items 会把技能触发源当成 null，导致后续被动全部不匹配。
                if (sourceItem == null)
                    foreach (InternalItem item in ctx.Skills)
                    {
                        if (item.Id == payload.SourceItemId)
                        {
                            sourceItem = item;
                            break;
                        }
                    }
            }

            foreach (InternalItem item in ctx.Items)
            {
                if (ctx.IsTrainingDummySource(item.Side) || !CanObserve(ctx, item, payload)) continue;
                bool deathOnce = payload.Event == "onPlayerDied" && IsOncePerFightDeathCard(item);
                if (deathOnce && item.OncePerFightUsed) continue;
                List<TriggerDef> matched = new List<TriggerDef>();
                foreach (TriggerDef trigger in Ordered(item.Card.Triggers))
                {
                    if (trigger.Event != payload.Event) continue;
                    if (!immediateOnly && payload.ImmediateSettled && trigger.Priority == "Immediate") continue;
                    if (!AttributesMatch(trigger, payload)) continue;
                    if (trigger.SkillRule != null)
                    {
                        if (payload.Global)
                        {
                            if (trigger.Filter != null || !GlobalMatches(ctx, item, trigger.SkillRule)) continue;
                        }
                        else if (trigger.SkillRule.PlayerOwner != null)
                        {
                            if (!PlayerMatches(ctx, item, payload, trigger)) continue;
                        }
                        else if (!NativeMatches(ctx, item, sourceItem, trigger, payload)) continue;
                    }
                    else
                    {
                        if (payload.Event == "onDamageTaken" && (!payload.TargetSide.HasValue || item.Side != payload.TargetSide.Value)) continue;
                        if ((payload.Event == "onDamageDealt" || payload.Event == "onUse" || SourceScoped.Contains(payload.Event)) && item.Side != payload.SourceSide) continue;
                    }

                    if (trigger.Filter != null)
                    {
                        if (trigger.Filter.SourceOther && (sourceItem == null || sourceItem.Id == item.Id)) continue;
                        if (trigger.Filter.SourceAdjacent && !AreAdjacent(ctx, item, sourceItem)) continue;
                        if (trigger.Filter.SourceFlyingOrFriend &&
                            (sourceItem == null || !sourceItem.Flying && !sourceItem.Card.Tags.Contains("Friend"))) continue;
                        if (!string.IsNullOrEmpty(trigger.Filter.SourceItemId) &&
                            trigger.Filter.SourceItemId != payload.SourceItemId)
                            continue;

                        if (!string.IsNullOrEmpty(trigger.Filter.SourceTag))
                        {
                            if (sourceItem == null ||
                                !sourceItem.Card.Tags.Contains(trigger.Filter.SourceTag))
                                continue;
                        }

                        if (trigger.Filter.TargetSide.HasValue &&
                            trigger.Filter.TargetSide.Value != payload.TargetSide)
                            continue;

                        if (trigger.Filter.Self && payload.TargetItemId != item.Id) continue;
                    }

                    matched.Add(trigger);
                }
                // 同一次事件里先完成本卡所有触发的前置判定，再按优先级结算。
                // “第一次”计数器（Custom_0）由后置计数能力 +1 时，不能反过来
                // 让同一事件的主效果在判定阶段看到已增加的值。
                List<TriggerDef> execute = PartitionByPass(payload, matched, item, false, immediateOnly);
                foreach (TriggerDef trigger in execute)
                {
                    ResolveMatched(ctx, new DeferredTriggerMatch { Owner = item, Trigger = trigger }, payload, time, nativeFrame);
                }
                if (deathOnce && matched.Count > 0) item.OncePerFightUsed = true;
            }

            foreach (InternalItem skill in ctx.Skills)
            {
                if (ctx.IsTrainingDummySource(skill.Side) || !CanObserve(ctx, skill, payload)) continue;
                bool deathOnce = payload.Event == "onPlayerDied" && IsOncePerFightDeathCard(skill);
                if (deathOnce && skill.OncePerFightUsed) continue;
                List<TriggerDef> matched = new List<TriggerDef>();
                foreach (TriggerDef trigger in Ordered(skill.Card.Triggers))
                {
                    if (trigger.Event != payload.Event || trigger.SkillRule == null) continue;
                    if (!immediateOnly && payload.ImmediateSettled && trigger.Priority == "Immediate") continue;
                    if (!AttributesMatch(trigger, payload)) continue;
                    bool matches = payload.Global
                        ? trigger.Filter == null && GlobalMatches(ctx, skill, trigger.SkillRule)
                        : trigger.SkillRule.PlayerOwner != null
                            ? PlayerMatches(ctx, skill, payload, trigger)
                            : NativeMatches(ctx, skill, sourceItem, trigger, payload);
                    if (!matches) continue;
                    matched.Add(trigger);
                }
                foreach (TriggerDef trigger in PartitionByPass(payload, matched, skill, true, immediateOnly))
                    ResolveMatched(ctx, new DeferredTriggerMatch { Owner = skill, Trigger = trigger, IsSkill = true }, payload, time, nativeFrame);
                if (deathOnce && matched.Count > 0) skill.OncePerFightUsed = true;
            }
        }

        // Immediate 分帧：ImmediatePass 时本帧只执行 Immediate 匹配；同帧判定
        // 通过的非 Immediate 匹配快照到载荷，下一帧执行（前提按使用帧状态为
        // 准，Immediate 计数 +1 不反噬）。所有监听者的延迟匹配都要保存，
        // 否则某张卡写入 DeferredMatches 后会让其他卡/技能的匹配被丢弃。
        private static List<TriggerDef> PartitionByPass(TriggerPayload payload, List<TriggerDef> matched,
            InternalItem owner, bool isSkill, bool immediatePass)
        {
            if (payload.BeforeUseStage != 0)
            {
                List<TriggerDef> executeBefore = new List<TriggerDef>();
                foreach (TriggerDef trigger in matched)
                {
                    if (payload.BeforeUseSettled != null && payload.BeforeUseSettled.Exists(
                        delegate(DeferredTriggerMatch old) { return old.Owner == owner && old.Trigger == trigger; })) continue;
                    // Medium observers run next frame and see Flying gained by
                    // the source's own effects (Marlon -> Flying Fish, frame 60/61).
                    if (trigger.Priority == "Medium")
                    {
                        if (payload.BeforeUseStage == 2)
                        {
                            if (payload.DeferredMatches == null) payload.DeferredMatches = new List<DeferredTriggerMatch>();
                            payload.DeferredMatches.Add(new DeferredTriggerMatch { Owner = owner, Trigger = trigger, IsSkill = isSkill });
                        }
                        continue;
                    }
                    executeBefore.Add(trigger);
                    if (payload.BeforeUseSettled == null) payload.BeforeUseSettled = new List<DeferredTriggerMatch>();
                    payload.BeforeUseSettled.Add(new DeferredTriggerMatch { Owner = owner, Trigger = trigger, IsSkill = isSkill });
                }
                return executeBefore;
            }
            if (matched.Count == 0 || !immediatePass) return matched;
            List<TriggerDef> immediate = new List<TriggerDef>(), deferred = new List<TriggerDef>();
            foreach (TriggerDef trigger in matched)
            {
                if (trigger.Priority == "Immediate") immediate.Add(trigger);
                else deferred.Add(trigger);
            }
            if (deferred.Count > 0)
            {
                if (payload.DeferredMatches == null) payload.DeferredMatches = new List<DeferredTriggerMatch>();
                foreach (TriggerDef trigger in deferred)
                    payload.DeferredMatches.Add(new DeferredTriggerMatch { Owner = owner, Trigger = trigger, IsSkill = isSkill });
            }
            return immediate;
        }

        // Artificial Heart / Sparring Partner 的模板没有 Custom_0 次数前提，
        // 但卡面分别是 “first time each fight” / “when you would be defeated”
        // 的一次性复活；按卡名锁一次，避免每次致死都重复满血/翻倍。
        private static bool IsOncePerFightDeathCard(InternalItem item)
        {
            if (item == null || item.Card == null) return false;
            string name = item.Card.DisplayName();
            if (name == "Artificial Heart" || name == "Sparring Partner" || name == "Sparring Partner (Skill)")
                return true;
            string native = NativeSkillSupport.Text(item.Card.NativeTemplate, "InternalName");
            return native == "Artificial Heart" || native == "Sparring Partner (Skill)";
        }

        // 全场事件（默认沙暴）没有 Source Item。只有不带 Subject/Source/Target
        // 过滤的触发器才允许在无来源时结算；带过滤的仍保持 fail-closed。
        private static bool GlobalMatches(BattleContext ctx, InternalItem owner, NativeSkillRule rule, bool checkPrerequisites = true)
        {
            if (rule == null) return true;
            if (rule.SourceOwner != null || rule.SourceCondition != null || rule.SourceSelf || rule.SourceOther ||
                rule.SourceAdjacent || rule.SourcePositionMode != null || rule.SourceXMostTarget != null) return false;
            if (rule.TargetOwner != null || rule.TargetSelf || rule.TargetOther || rule.TargetPositionMode != null ||
                rule.TargetIsPlayer || rule.TargetCondition != null) return false;
            if (rule.ActorOwner != null || rule.ActorSelf || rule.ActorOther || rule.ActorPositionMode != null ||
                rule.ActorCondition != null) return false;
            if (rule.PlayerOwner != null || rule.PlayerCondition != null) return false;
            return !checkPrerequisites || NativeSkillSupport.PrerequisitesMatch(ctx, owner, rule);
        }

        private static bool NativeMatches(BattleContext ctx, InternalItem owner, InternalItem source, TriggerDef trigger, TriggerPayload payload, bool checkPrerequisites = true)
        {
            NativeSkillRule rule = trigger.SkillRule;
            if (source == null || rule == null) return false;
            if (!NativeSkillSupport.OwnerMatches(rule.SourceOwner, owner.Side, source.Side)) return false;
            if (rule.SourceSelf && source.Id != owner.Id || rule.SourceOther && source.Id == owner.Id || rule.SourceAdjacent && !AreAdjacent(ctx, owner, source)) return false;
            if (rule.SourceOccupying && (source.Slot != owner.Slot || !NativeSkillSupport.IsSocketEffect(owner))) return false;
            if (rule.SourcePositionMode != null && !NativeSkillSupport.PositionalMatch(ctx, owner, source, rule.SourcePositionMode, rule.IncludeOrigin)) return false;
            if (rule.SourceXMostTarget != null)
            {
                List<InternalItem> selected = Effects.NativeItemsForTarget(ctx, owner, rule.SourceXMostTarget, 1, null);
                if (!selected.Exists(delegate(InternalItem candidate) { return candidate.Id == source.Id; })) return false;
            }
            if (!NativeSkillSupport.CardMatches(source, rule.SourceCondition, ctx, payload.SourceItemId) ||
                checkPrerequisites && !NativeSkillSupport.PrerequisitesMatch(ctx, owner, rule, payload.SourceItemId)) return false;
            return ActorMatches(ctx, owner, rule, payload) && TargetMatches(ctx, owner, rule, payload);
        }

        // 修理／变形／摧毁前：Subject 是被影响的卡，Trigger.Source 才是行动者。
        private static bool ActorMatches(BattleContext ctx, InternalItem owner, NativeSkillRule rule, TriggerPayload payload)
        {
            if (rule.ActorOwner == null) return true;
            InternalItem actor = FindItem(ctx, payload.ActorItemId);
            if (actor == null) return false;
            if (!NativeSkillSupport.OwnerMatches(rule.ActorOwner, owner.Side, actor.Side)) return false;
            if (rule.ActorSelf && actor.Id != owner.Id || rule.ActorOther && actor.Id == owner.Id) return false;
            if (rule.ActorOccupying && (actor.Slot != owner.Slot || !NativeSkillSupport.IsSocketEffect(owner))) return false;
            if (rule.ActorPositionMode != null && !NativeSkillSupport.PositionalMatch(ctx, owner, actor, rule.ActorPositionMode, rule.ActorIncludeOrigin)) return false;
            return NativeSkillSupport.CardMatches(actor, rule.ActorCondition, ctx, payload.ActorItemId);
        }

        // Trigger.Target 是行动受体：卡牌事件核对具体卡，英雄事件核对阵营。
        private static bool TargetMatches(BattleContext ctx, InternalItem owner, NativeSkillRule rule, TriggerPayload payload)
        {
            if (rule.TargetIsPlayer)
            {
                if (!payload.TargetSide.HasValue) return false;
                bool sameSide = payload.TargetSide.Value == owner.Side;
                if (rule.TargetPlayerOwner == "self" ? !sameSide : sameSide) return false;
                return NativeSkillSupport.PlayerConditionMatches(ctx, ctx.Hero(payload.TargetSide.Value), rule.TargetPlayerCondition, owner.Side);
            }
            if (rule.TargetOwner == null) return true;
            InternalItem target = FindItem(ctx, payload.TargetItemId);
            if (target == null) return false;
            if (!NativeSkillSupport.OwnerMatches(rule.TargetOwner, owner.Side, target.Side)) return false;
            if (rule.TargetSelf && target.Id != owner.Id || rule.TargetOther && target.Id == owner.Id) return false;
            if (rule.TargetOccupying && (target.Slot != owner.Slot || !NativeSkillSupport.IsSocketEffect(owner))) return false;
            if (rule.TargetPositionMode != null && !NativeSkillSupport.PositionalMatch(ctx, owner, target, rule.TargetPositionMode, rule.TargetIncludeOrigin)) return false;
            return NativeSkillSupport.CardMatches(target, rule.TargetCondition, ctx, payload.TargetItemId);
        }

        private static InternalItem FindItem(BattleContext ctx, string itemId)
        {
            if (string.IsNullOrEmpty(itemId)) return null;
            foreach (InternalItem item in ctx.Items)
                if (item.Id == itemId) return item;
            return null;
        }

        // 人物事件（受伤、暴怒、死亡）的匹配集合是英雄，不是卡牌。
        private static bool PlayerMatches(BattleContext ctx, InternalItem owner, TriggerPayload payload, TriggerDef trigger)
        {
            NativeSkillRule rule = trigger.SkillRule;
            bool sideMatches = rule.PlayerOwner == "self" ? payload.SourceSide == owner.Side : payload.SourceSide != owner.Side;
            if (!sideMatches) return false;
            if (!NativeSkillSupport.PlayerConditionMatches(ctx, ctx.Hero(payload.SourceSide), rule.PlayerCondition, owner.Side)) return false;
            return NativeSkillSupport.PrerequisitesMatch(ctx, owner, rule);
        }

        private static bool AttributesMatch(TriggerDef trigger, TriggerPayload payload)
        {
            if (trigger.AttributeFilter == null) return true;
            if (!string.Equals(trigger.AttributeFilter, payload.AttributeName, StringComparison.OrdinalIgnoreCase)) return false;
            return trigger.ChangeType == null || string.Equals(trigger.ChangeType, payload.ChangeType, StringComparison.OrdinalIgnoreCase);
        }

        // 原生 EffectPriority 从 Lowest 到 Immediate 递增；同一张卡按
        // Immediate 先、Lowest 后。ResolvePayload 先收集全部匹配触发再执行
        // 效果，因此前提在计数器递增前已判定，Memento Mori 的复活不会被
        // Immediate 的计数器抢跑。
        private static IEnumerable<TriggerDef> Ordered(List<TriggerDef> triggers)
        {
            return triggers.OrderBy(delegate(TriggerDef trigger) { return PriorityRank(trigger.Priority); });
        }

        private static int PriorityRank(string priority)
        {
            if (priority == "Immediate") return 0;
            if (priority == "Highest") return 1;
            if (priority == "High") return 2;
            if (priority == "Low") return 4;
            if (priority == "Lowest") return 5;
            return 3;
        }

        private static bool AreAdjacent(BattleContext ctx, InternalItem item, InternalItem source)
        {
            if (source == null || source.Side != item.Side || source.Id == item.Id) return false;
            // Native Neighbor selects the next occupied item on either side.
            foreach (InternalItem between in ctx.Items)
            {
                if (between.Destroyed || between.Side != item.Side || between.Id == item.Id || between.Id == source.Id) continue;
                if (between.Slot > System.Math.Min(item.Slot, source.Slot) &&
                    between.Slot < System.Math.Max(item.Slot, source.Slot)) return false;
            }
            return true;
        }
    }
